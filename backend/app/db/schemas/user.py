from datetime import datetime
import uuid as UUID

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    Enum as SQLAlchemyEnum,
    String,
    func,
)
from sqlalchemy.dialects.postgresql import UUID as PostgreSQLUUID
from sqlalchemy.orm import Mapped, mapped_column


from app.db.base import Base
from app.enums import Occupation



class UserTable(Base):
    __tablename__ = "user_table"

    __table_args__ = (
        CheckConstraint(
            "char_length(trim(first_name)) >= 2",
            name="ck_profiles_first_name_length",
        ),
        CheckConstraint(
            "char_length(trim(last_name)) >= 2",
            name="ck_profiles_last_name_length",
        ),
        CheckConstraint(
            "char_length(trim(username)) >= 3",
            name="ck_profiles_username_length",
        ),
        CheckConstraint(
            "age BETWEEN 3 AND 120",
            name="ck_profiles_age_range",
        ),
        CheckConstraint(
            "char_length(trim(university)) >= 5",
            name="ck_profiles_university_length",
        ),
        CheckConstraint(
            """
            occupation != 'Other'
            OR (
                occupation_other IS NOT NULL
                AND char_length(trim(occupation_other)) >= 5
            )
            """,
            name="ck_profiles_other_occupation",
        ),
    )

    # Use the UUID generated by Supabase Auth.
    # Assign it when creating the profile; do not generate another UUID.
    id: Mapped[UUID] = mapped_column(
        PostgreSQLUUID(as_uuid=True),
        primary_key=True,
    )

    first_name: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
    )

    last_name: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
    )

    username: Mapped[str] = mapped_column(
        String(100),
        unique=True,
        nullable=False,
        index=True,
    )

    email: Mapped[str] = mapped_column(
        String(255),
        unique=True,
        nullable=False,
        index=True,
    )

    age: Mapped[int] = mapped_column(
        nullable=False,
    )

    university: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
    )

    occupation: Mapped[Occupation] = mapped_column(
        SQLAlchemyEnum(
            Occupation,
            name="occupation_enum",
            values_callable=lambda enum_cls: [
                item.value for item in enum_cls
            ],
        ),
        nullable=False,
    )

    occupation_other: Mapped[str | None] = mapped_column(
        String(255),
        nullable=True,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )
